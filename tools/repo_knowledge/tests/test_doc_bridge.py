from __future__ import annotations

import subprocess
import sys
import tempfile
import unittest
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[3]
BRIDGE = REPO_ROOT / "tools" / "doc_bridge.py"


class DocumentationBridgeTests(unittest.TestCase):
    def run_bridge(self, *args: str) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [sys.executable, str(BRIDGE), *args],
            check=True,
            capture_output=True,
            text=True,
        )

    def test_fix_replaces_stale_private_registry_link(self) -> None:
        with tempfile.TemporaryDirectory(prefix="ternux-doc-bridge-") as temp:
            root = Path(temp)
            (root / ".repo").mkdir()
            (root / ".repo" / "STATUS.md").write_text("generated\n", encoding="utf-8")
            readme = root / "README.md"
            readme.write_text(
                "<!-- deterministic-state-bridge: ternux -->\n\n"
                "**Machine-generated operational state:** see "
                "[`.repo/STATUS.md`](./.repo/STATUS.md) (generated by `tools/repo_knowledge`). "
                "For cross-project SKB registry state, see "
                "[`ternux.json`](https://github.com/soobujmiah/skb/blob/main/"
                "projects/registry/ternux.json).\n\n# Ternux\n",
                encoding="utf-8",
            )

            self.run_bridge("fix", "--project-id", "ternux", str(readme))
            self.run_bridge("check", "--strict", "--project-id", "ternux", str(readme))

            updated = readme.read_text(encoding="utf-8")
            self.assertIn("[`.repo/STATUS.md`](.repo/STATUS.md)", updated)
            self.assertNotIn("soobujmiah/skb", updated)

    def test_fix_adds_a_resolvable_local_status_link(self) -> None:
        with tempfile.TemporaryDirectory(prefix="ternux-doc-bridge-") as temp:
            root = Path(temp)
            (root / ".repo").mkdir()
            (root / ".repo" / "STATUS.md").write_text("generated\n", encoding="utf-8")
            readme = root / "README.md"
            readme.write_text("# Ternux\n", encoding="utf-8")

            self.run_bridge("fix", "--project-id", "ternux", str(readme))
            self.run_bridge("check", "--strict", "--project-id", "ternux", str(readme))

            self.assertIn("<!-- deterministic-state-bridge: ternux -->", readme.read_text(encoding="utf-8"))


if __name__ == "__main__":
    unittest.main()
